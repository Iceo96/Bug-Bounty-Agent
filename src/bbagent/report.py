"""Markdown report generation for verified findings.

Reports are built strictly from stored data and integrity-verified evidence.
No severity is assigned unless a program-specific methodology provides one.
"""

from __future__ import annotations

import json
from typing import Optional

from bbagent.storage.db import Database
from bbagent.storage.evidence import EvidenceStore
from bbagent.storage.models import Finding


def _fmt_evidence(store: EvidenceStore, evidence_id: str) -> str:
    """Return a fenced block for one evidence blob, verifying integrity first."""
    data = store.read_verified(evidence_id)  # raises on tampering
    try:
        pretty = json.dumps(json.loads(data), indent=2)
    except (json.JSONDecodeError, UnicodeDecodeError):
        pretty = data.decode("utf-8", errors="replace")
    return f"```\n{pretty}\n```"


def generate_report(
    finding: Finding,
    db: Database,
    evidence: EvidenceStore,
    *,
    severity: Optional[str] = None,
) -> str:
    """Render a Markdown report for a single verified finding.

    ``severity`` is included only if the caller passes one (i.e. a program-
    specific methodology exists). Otherwise the field is omitted.
    """
    lines: list[str] = []
    lines.append(f"# {finding.title}")
    lines.append("")

    # Deterministic completeness check: mark incomplete rather than guessing.
    from bbagent.validation import report_quality

    quality = report_quality(finding, db, evidence)
    if not quality.complete:
        lines.append(f"> ⚠️ **INCOMPLETE REPORT** — missing/failed: {', '.join(quality.issues)}.")
        lines.append("> This report is not ready for submission. No information has been invented.")
        lines.append("")
    lines.append(f"- **Program:** {finding.program}")
    lines.append(f"- **Status:** {finding.status.value}")
    lines.append(f"- **Vulnerability type:** {finding.vuln_type}")
    if severity:
        lines.append(f"- **Severity:** {severity}")
    lines.append(f"- **Affected asset:** {finding.affected_asset}")
    lines.append(f"- **Endpoint:** `{finding.http_method} {finding.endpoint}`")
    lines.append(f"- **Test identity:** {finding.test_identity}")
    lines.append("")

    lines.append("## Summary")
    lines.append(finding.impact or "_No summary provided._")
    lines.append("")

    if finding.preconditions:
        lines.append("## Preconditions")
        lines.append(finding.preconditions)
        lines.append("")

    lines.append("## Steps to reproduce")
    lines.append(finding.reproduction or "_See evidence below._")
    lines.append("")

    lines.append("## Expected behavior")
    lines.append(finding.expected_behavior or "_Not specified._")
    lines.append("")

    lines.append("## Actual behavior")
    lines.append(finding.actual_behavior or "_Not specified._")
    lines.append("")

    lines.append("## Impact")
    lines.append(finding.impact or "_Not specified._")
    lines.append("")

    lines.append("## Evidence")
    if not finding.evidence_ids:
        lines.append("_No evidence attached — this finding is not valid._")
    for eid in finding.evidence_ids:
        rec = db.get_evidence(eid)
        label = rec.label if rec else "evidence"
        sha = rec.sha256[:12] if rec else "?"
        lines.append(f"### {label} (`{eid}`, sha256 `{sha}`)")
        lines.append(_fmt_evidence(evidence, eid))
        lines.append("")

    lines.append("---")
    lines.append(
        "_Generated by bbagent. This report requires human review before submission. "
        "The agent does not submit reports._"
    )
    return "\n".join(lines)
